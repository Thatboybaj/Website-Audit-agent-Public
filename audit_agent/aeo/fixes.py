"""Ready-to-paste AEO fixes generated from the site itself (Pro deliverables).
Nothing here is invented: every value comes from the crawled pages or from AI output the user can review."""
from __future__ import annotations

import json
import re
from urllib.parse import urlparse

from ..crawler import SiteData
from .bots import BOTS
from .checks import SOCIAL_RX


def _title(p) -> str:
    return (p.soup.title.string or "").strip() if p.soup and p.soup.title and p.soup.title.string else ""


def _desc(p) -> str:
    if p.soup and (m := p.soup.find("meta", attrs={"name": re.compile("^description$", re.I)})):
        return (m.get("content") or "").strip()
    return ""


def brand_name(site: SiteData, ld: dict) -> str:
    for o in ld.get("Organization", []) + ld.get("LocalBusiness", []):
        if o.get("name"):
            return str(o["name"]).strip()
    home = site.home
    if home and home.soup:
        if (m := home.soup.find("meta", property="og:site_name")) and m.get("content"):
            return m["content"].strip()
        t = _title(home)
        if t:
            parts = re.split(r"\s[|–—·-]\s", t)
            return (parts[-1] if len(parts) > 1 else parts[0]).strip()
    return urlparse(site.origin).hostname or "Website"


def llms_txt(site: SiteData, brand: str, summary: str = "") -> str:
    home = site.home
    summary = summary or (_desc(home) if home else "") or f"Official website of {brand}."
    groups: dict[str, list[str]] = {}
    seen = set()
    for p in site.html_pages:
        u = p.final_url.split("#")[0]
        if "?" in u or u in seen:
            continue
        robots = p.soup.find("meta", attrs={"name": re.compile("^robots$", re.I)}) if p.soup else None
        if robots and "noindex" in (robots.get("content") or "").lower():
            continue
        seen.add(u)
        path = urlparse(p.final_url).path.strip("/")
        sec = "Main pages" if path.count("/") == 0 else path.split("/")[0].replace("-", " ").title()
        t = _title(p) or path or brand
        t = re.split(r"\s[|–—·]\s", t)[0].strip()
        d = _desc(p)
        groups.setdefault(sec, []).append(f"- [{t}]({p.final_url})" + (f": {d}" if d else ""))
    out = [f"# {brand}", "", f"> {summary}", ""]
    for sec, items in groups.items():
        out += [f"## {sec}", "", *list(dict.fromkeys(items))[:25], ""]
    return "\n".join(out).strip() + "\n"


def robots_block(training: str = "allow") -> str:
    lines = ["# --- AI crawlers (generated by AuditPilot) ---",
             "# Search & live-fetch bots: allow these to be cited in AI answers"]
    for b in BOTS:
        if b["role"] in ("search", "user"):
            lines += [f"User-agent: {b['name']}", "Allow: /", ""]
    lines.append("# Training bots: " + ("allowed (max AI exposure)" if training == "allow" else "blocked (opt out of model training)"))
    for b in BOTS:
        if b["role"] == "training":
            lines += [f"User-agent: {b['name']}", "Allow: /" if training == "allow" else "Disallow: /", ""]
    return "\n".join(lines).strip() + "\n"


def organization(site: SiteData, brand: str, ld: dict) -> str:
    home = site.home
    soup = home.soup if home else None
    html = "\n".join(p.html for p in site.html_pages)
    same = sorted({h for p in site.html_pages for h in p.external_links if SOCIAL_RX.search(h)})[:10]
    logo = None
    if soup:
        if (m := soup.find("meta", property="og:image")) and m.get("content"):
            logo = m["content"]
    logo = logo or (site.extras.get("favicon") or {}).get("url")
    tel = re.search(r'href=["\']tel:([^"\']+)', html)
    mail = re.search(r'href=["\']mailto:([^"\'?]+)', html)
    obj = {"@context": "https://schema.org", "@type": "Organization", "name": brand, "url": site.origin + "/"}
    if logo:
        obj["logo"] = logo
    if home and _desc(home):
        obj["description"] = _desc(home)
    if same:
        obj["sameAs"] = same
    if tel or mail:
        cp = {"@type": "ContactPoint", "contactType": "customer service"}
        if tel:
            cp["telephone"] = tel.group(1).strip()
        if mail:
            cp["email"] = mail.group(1).strip()
        obj["contactPoint"] = cp
    return json.dumps(obj, indent=2, ensure_ascii=False)


def website(site: SiteData, brand: str) -> str:
    return json.dumps({"@context": "https://schema.org", "@type": "WebSite", "name": brand, "url": site.origin + "/"}, indent=2)


def faq(qs: list[dict], ai_faq: list[dict] | None = None) -> tuple[str, str]:
    """FAQPage JSON-LD from Q&A found on the site; falls back to AI-drafted pairs (marked for review)."""
    pairs = [(q["q"], q["a"]) for q in qs if 8 <= q["words"] <= 120][:8]
    source = "site"
    if not pairs and ai_faq:
        pairs = [(x.get("q", ""), x.get("a", "")) for x in ai_faq if x.get("q") and x.get("a")][:6]
        source = "ai"
    if not pairs:
        return "", "none"
    obj = {"@context": "https://schema.org", "@type": "FAQPage", "mainEntity": [
        {"@type": "Question", "name": q, "acceptedAnswer": {"@type": "Answer", "text": a}} for q, a in pairs]}
    return json.dumps(obj, indent=2, ensure_ascii=False), source


def build(site: SiteData, brand: str, ld: dict, qs: list, ai_eval: dict | None) -> dict:
    ai_eval = ai_eval or {}
    faq_json, faq_src = faq(qs, ai_eval.get("faq"))
    fixes = {
        "llms_txt": {"title": "llms.txt", "file": "/llms.txt", "lang": "markdown",
                     "how": "Save as llms.txt at your site root (e.g. upload in Framer/Webflow 'static files' or your /public folder).",
                     "code": llms_txt(site, brand, ai_eval.get("summary", ""))},
        "robots": {"title": "robots.txt — AI crawler rules", "file": "/robots.txt", "lang": "text",
                   "how": "Add to your robots.txt (keep your existing rules). Training bots are allowed by default — switch to Disallow to opt out of training.",
                   "code": robots_block("allow")},
        "organization": {"title": "Organization schema", "file": "<head>", "lang": "json",
                         "how": "Paste inside <script type=\"application/ld+json\"> in your homepage <head>. Check every value before publishing.",
                         "code": organization(site, brand, ld)},
        "website": {"title": "WebSite schema", "file": "<head>", "lang": "json",
                    "how": "Paste inside <script type=\"application/ld+json\"> on the homepage.", "code": website(site, brand)},
    }
    if faq_json:
        fixes["faq"] = {"title": "FAQPage schema", "file": "<head>", "lang": "json",
                        "how": ("Built from the Q&A on your pages." if faq_src == "site" else
                                "AI-drafted from your content — review the answers, add them visibly to the page, then add this markup.")
                        + " Paste inside <script type=\"application/ld+json\"> on the page that shows these questions.",
                        "code": faq_json}
    if ai_eval.get("intro"):
        fixes["intro"] = {"title": "Quotable intro sentence", "file": "Homepage", "lang": "text",
                          "how": "Use as the first sentence on your homepage/About page — this is what AI assistants quote.",
                          "code": ai_eval["intro"]}
    return fixes
